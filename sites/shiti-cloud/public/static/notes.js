export function mountNoteEditor({root, pid, number, toast, flush}) {
  const textarea = root.querySelector('#note'), preview = root.querySelector('.note-preview');
  const status = root.querySelector('.note-upload-status');
  function openImage(event) {
    const image = event.target.closest('img');
    if (!image || (event.type === 'keydown' && !['Enter', ' '].includes(event.key))) return;
    event.preventDefault();window.open(image.src, '_blank', 'noopener,noreferrer');
  }
  preview.addEventListener('click', openImage);
  preview.addEventListener('keydown', openImage);
  let operation = null, previewTimer, mode = 'edit';
  const showPreview = () => {
    clearTimeout(previewTimer);
    preview.innerHTML = textarea.value.trim() ? renderMarkdown(textarea.value) : '<p class="note-placeholder">还没有笔记，切回编辑写下第一条思路。</p>';
    preview.querySelectorAll('img').forEach(img => img.addEventListener('error', () => {
      const message = document.createElement('span');
      message.className = 'note-image-missing';message.textContent = `图片加载失败：${img.alt || '请检查图片地址'}`;
      img.replaceWith(message);
    }, {once:true}));
  };
  function setMode(next) {
    mode = next;root.dataset.mode = mode;
    textarea.hidden = mode === 'preview';preview.hidden = mode === 'edit';
    root.querySelectorAll('[data-note-mode]').forEach(button => {
      const active = button.dataset.noteMode === mode;
      button.classList.toggle('active', active);button.setAttribute('aria-pressed', String(active));
    });
    root.querySelector('.note-tools').hidden = mode === 'preview';
    if (mode !== 'edit') showPreview();
  }
  function insert(text, start = textarea.selectionStart, end = textarea.selectionEnd) {
    if (textarea.value.length - (end - start) + text.length > textarea.maxLength) throw new Error('笔记最多支持 100000 个字符，请分段整理');
    textarea.setRangeText(text, start, end, 'end');
    textarea.dispatchEvent(new Event('input', {bubbles:true}));
  }
  function format(kind) {
    const selected = textarea.value.slice(textarea.selectionStart, textarea.selectionEnd);
    if (kind === 'bold') insert(`**${selected || '重点'}**`);
    if (kind === 'heading') insert(`\n## ${selected || '错因分析'}\n`);
    if (kind === 'list') insert('\n' + (selected || '复习要点').split('\n').map(line => '- ' + line).join('\n') + '\n');
    textarea.focus();
  }
  function run(task) {
    if (operation) { toast('正在处理图片或文件，请稍候');return operation; }
    textarea.readOnly = true;
    root.querySelectorAll('.note-tools button').forEach(button => button.disabled = true);
    operation = Promise.resolve().then(task).catch(error => {
      status.textContent = error.message;toast(error.message);
    }).finally(() => {
        textarea.readOnly = false;
        root.querySelectorAll('.note-tools button').forEach(button => button.disabled = false);
        operation = null;
    });
    return operation;
  }
  function upload(files) {
    return run(async () => {
      for (const [index, file] of files.entries()) {
        if (!['image/png','image/jpeg','image/gif','image/webp'].includes(file.type)) throw new Error('请选择 PNG、JPEG、GIF 或 WebP 图片');
        if (!file.size || file.size > 10 * 1024 * 1024) throw new Error('每张图片不能为空且不能超过 10 MB');
        status.textContent = `正在上传图片 ${index + 1} / ${files.length}…`;
        const controller = new AbortController(), timer = setTimeout(() => controller.abort(), 30000);
        try {
          const response = await fetch(`/api/questions/${pid}/${number}/images`, {method:'POST',headers:{'Content-Type':file.type},body:file,signal:controller.signal});
          const result = await response.json();
          if (response.status === 404 && result.detail === 'Not Found') throw new Error('拾题后台仍是旧版本，请重启拾题服务并刷新网页，再粘贴图片。');
          if (!response.ok) throw new Error(typeof result.detail === 'string' ? result.detail : '图片上传失败，请重试');
          const alt = file.name.replace(/\.[^.]+$/, '').replace(/[\[\]\\\r\n<>]/g, '') || '笔记图片';
          insert(`\n![${alt}](${result.url})\n`);
        } finally { clearTimeout(timer); }
      }
      status.textContent = `已插入 ${files.length} 张图片`;
      setMode('split');
    });
  }
  function importMarkdown(file) {
    return run(async () => {
      if (!/\.(md|markdown)$/i.test(file.name)) throw new Error('请选择 .md 或 .markdown 文件');
      if (file.size > 1024 * 1024) throw new Error('Markdown 文件不能超过 1 MB');
      status.textContent = '正在导入 Markdown…';
      const text = (await file.text()).replace(/^\uFEFF/, '');
      insert((textarea.value ? '\n\n' : '') + text);
      setMode('split');
      status.textContent = '已导入；文件中的本地图片需另行上传。';
    });
  }
  root.addEventListener('click', async event => {
    const button = event.target.closest('button');if (!button || button.disabled) return;
    try {
      if (button.dataset.noteMode) setMode(button.dataset.noteMode);
      if (button.dataset.noteFormat) format(button.dataset.noteFormat);
      if (button.dataset.noteCommand === 'image') root.querySelector('.note-image-input').click();
      if (button.dataset.noteCommand === 'import') root.querySelector('.note-md-input').click();
      if (button.dataset.noteCommand === 'export' && await flush()) {
        const url = URL.createObjectURL(new Blob([textarea.value], {type:'text/markdown;charset=utf-8'}));
        const link = document.createElement('a');link.href = url;link.download = `笔记-${pid}-第${number}题.md`;link.click();
        setTimeout(() => URL.revokeObjectURL(url), 1000);
        toast('Markdown 已导出；迁移图片请使用「备份与恢复」');
      }
    } catch (error) { toast(error.message); }
  });
  root.querySelector('.note-image-input').addEventListener('change', event => {
    const files = [...event.target.files];event.target.value = '';if (files.length) upload(files);
  });
  root.querySelector('.note-md-input').addEventListener('change', event => {
    const file = event.target.files[0];event.target.value = '';if (file) importMarkdown(file);
  });
  textarea.addEventListener('input', () => { if (mode !== 'edit') {clearTimeout(previewTimer);previewTimer = setTimeout(showPreview, 150);} });
  textarea.addEventListener('keydown', event => {
    if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === 'b' && !operation) {event.preventDefault();format('bold');}
  });
  root.addEventListener('paste', event => {
    const files = [...(event.clipboardData?.items || [])].filter(item => item.kind === 'file').map(item => item.getAsFile()).filter(Boolean);
    if (files.length) {event.preventDefault();upload(files);}
  });
  root.addEventListener('dragover', event => {
    if (event.dataTransfer.types.includes('Files')) {event.preventDefault();root.classList.add('drag-over');}
  });
  root.addEventListener('dragleave', event => {if (!root.contains(event.relatedTarget)) root.classList.remove('drag-over');});
  root.addEventListener('drop', event => {
    root.classList.remove('drag-over');const files = [...event.dataTransfer.files];if (!files.length) return;
    event.preventDefault();
    if (files.length === 1 && /\.(md|markdown)$/i.test(files[0].name)) importMarkdown(files[0]);else upload(files);
  });
  return {get busy() { return !!operation; }, async wait() { if (operation) await operation; }};
}
