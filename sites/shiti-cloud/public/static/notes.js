import {Marked} from './vendor/marked.js';
import {mathExtensions} from './note-math.js?v=1';

const escapeHTML = value => String(value ?? '').replace(/[&<>"']/g, ch => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch]));
function safeURL(value, image = false) {
  const url = String(value || '').trim();
  if (/[\u0000-\u0020\u007f]/.test(url)) return null;
  if (/^https?:\/\//i.test(url) || /^\/(?![\/\\])/.test(url)) return url;
  if (!image && (/^mailto:/i.test(url) || /^#[^\s]*$/.test(url))) return url;
  return null;
}
// Raw HTML is displayed literally. URLs are allowlisted before entering attributes.
// All other markup is generated by Marked's built-in renderers, offline.
const markdown = new Marked({gfm:true, breaks:true, renderer:{
  html({text}) { return escapeHTML(text); },
  link({href, tokens}) {
    const label = this.parser.parseInline(tokens), url = safeURL(href);
    return url ? `<a href="${escapeHTML(url)}" target="_blank" rel="noopener noreferrer">${label}</a>` : label;
  },
  image({href, text}) {
    const url = safeURL(href, true);
    return url ? `<img src="${escapeHTML(url)}" alt="${escapeHTML(text)}" loading="lazy" referrerpolicy="no-referrer" tabindex="0" role="button" title="点击查看原图">` : `<span class="note-image-missing">[图片：${escapeHTML(text || '请上传本地图片')}]</span>`;
  }
}});
markdown.use(mathExtensions);

export function renderMarkdown(value) { return markdown.parse(value); }

